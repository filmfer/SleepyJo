#!/usr/bin/env python3
"""Generate sleepyjo/locales_data.py from locales/*.json.

Embedding translations as a Python module makes them survive PyInstaller
packaging (package-data JSONs are not collected automatically), fixing raw
"menu_..." keys in frozen builds.
"""

import json
import sys
from pathlib import Path

root = Path(__file__).resolve().parent.parent
locales = root / "sleepyjo" / "locales"
data = {}
for path in sorted(locales.glob("*.json")):
    data[path.stem] = json.loads(path.read_text(encoding="utf-8"))

out = root / "sleepyjo" / "locales_data.py"
lines = ["\"\"\"Auto-generated by tools/gen_locales.py - do not edit.\"\"\"", ""]
lines.append("LOCALES = {")
for lang, strings in data.items():
    lines.append(f"    {lang!r}: {{")
    for key, value in strings.items():
        lines.append(f"        {key!r}: {value!r},")
    lines.append("    },")
lines.append("}")
out.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"Generated {out} ({len(data)} languages, "
      f"{sum(len(v) for v in data.values())} strings)")
